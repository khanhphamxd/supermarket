package com.example.supermarket.model;

import java.math.BigDecimal; //used for exact decimal values
//Jakarta Persistance imports
import jakarta.persistence.Entity; 
import jakarta.persistence.GeneratedValue; 
import jakarta.persistence.GenerationType; 
import jakarta.persistence.Id; 

@Entity //Mark this class as an entity, allowing it to be mapped as a database table 
public class Product {
    
    @Id //Mark this field as the database's primary key
    @GeneratedValue (strategy = GenerationType.IDENTITY)
    private Long id;
    /*@Id: Mark the value as the primary key of the database
    @GeneratedValue: Assign this value to be generated by the database
    GenerationType.IDENTITY: Select the strategy to generate values 
    (IDENTITY: let the database generate an identity value, typically increasing for each row) */

    private String name; //Product's name
    private String description; //Product's description
    private String category; //Product's category
    private BigDecimal price; // Product's price

    protected Product() {
        //JPA-required no-parameter constructor
    }

    public Product(String name, String description, String category, BigDecimal price) {
        // this.id = id;        As the database is now in charge of generating ids, we don't need to construct them anymore
        this.name = name;
        this.description = description;
        this.category = category;
        this.price = price;
    }

    public Long getId() {
        return id;
    }
    
    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }
    
    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public String getCategory() {
        return category;
    }

    public void setCategory(String category) {
        this.category = category;
    }
    
    public BigDecimal getPrice() {
        return price;
    }

    public void setPrice(BigDecimal price) {
        this.price = price;
    }

    @Override // Override the default toString() method
    // Write out the product's attribute into 1 line
    public String toString() {
        return id + " - " + name + " - " + description + " - " + category + " - " + price;
    }
}
